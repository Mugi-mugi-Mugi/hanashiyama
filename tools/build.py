def clean_name(s):
    """「奈良公園の鹿（国の天然記念物）」→「奈良公園の鹿」。語りに括弧・注記を持ち込まない"""
    for l, r in [("（", "）"), ("(", ")")]:
        while l in s and r in s[s.index(l):]:
            s = s[:s.index(l)] + s[s.index(l) + s[s.index(l):].index(r) + 1:]
    return " ".join(s.split()).replace(" ", "").strip("・、 ")


def load_kakeizu(path):
    """レッサーパンダ家系図から ★層=確定 の 転出行だけを 読む (★2026-09-23)。

    ★使ってよい線引き (家系図の吟味 §6)
      ・★層が「確定」の行だけ。★「参考」105 行と「除外」27 行は 使わない
        (図の中の文字を 機械で 起こしたもので、抽出の壊れを 実測で 27 件 数えた)
      ・★方向が「転出」= 箱に「〜へ」と 書いてある行だけ。「所在(明示なし)」は 渡ったと 書かれていない
      ・★語ってよいのは ★都道府県まで。★園の 略称からの 推定には 誤りが あった
      ・★名前と 生年は ★飼育個体情報と 突き合わせる 鍵として だけ 使う (語りには 出さない)
      ・★施設名と 日付は ★飼育個体情報 (redpanda_moves.csv) から 取る
    戻り: {(名前, 生年4桁): {"pref": 行き先の県, "rel": 貸出|交換|譲渡|寄贈}}
    """
    if not os.path.exists(path):
        return {}
    out = {}
    with open(path, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            if r.get("層") != "確定" or r.get("方向") != "転出":
                continue
            name, year = (r.get("名前") or "").strip(), (r.get("生年") or "").strip()[:4]
            if not name or not year:
                continue
            out[(name, year)] = {"pref": (r.get("pref") or "").strip(),
                                 "rel": (r.get("関係") or "").strip()}
    return out


def variant(pref, arr):
    """県ごとに 言い回しを 変える (同じサゲが 並ばないように)。

    ★2026-09-25: 文字コードの 単純な 足し算だと ★似た名前が 同じ 番号に 寄る。
      (47 県を 4 本に 割ると 15/14/9/9。理想は 11.8)
      → ★桁を 混ぜる 足し方に して、散りを よくする。
      ★候補の 本数以上には 増えない ので、候補そのものも 増やしてある。
    """
    h = 0
    for i, c in enumerate(pref):
        h = (h * 131 + ord(c) * (i + 7)) & 0xFFFFFFFF
    return arr[h % len(arr)]


def flatten_hondai(stories):
    """本題の台詞 ({"who","text"}) を 文字列に ならした コピーを 返す。

    ★本題は 地の文と 台詞の 混在に なった (2026-09-22)。
      文字列だけを 前提に している 書き出しに 渡すときは、ここを 通す。
    """
    out = []
    for s in stories:
        t = dict(s)
        t["hondai"] = [h if isinstance(h, str) else (h.get("who", "") + "「" + h.get("text", "") + "」")
                       for h in s.get("hondai", [])]
        out.append(t)
    return out


