def main():
    facts = load_json(P("app", "data", "facts.json"))
    stories = load_json(P("app", "data", "stories.json"))
    with open(P("data", "derived", "redpanda_moves.csv"), encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    meibutsu = load_json(P("data", "derived", "pref_meibutsu.json"))["items"]
    zoos = load_json(P("data", "derived", "redpanda_zoos.json"))["items"]
    keywords = load_json(P("data", "derived", "keyword_map.json"))["entries"]
    # ★家系図は 「どの県と 縁が あるか」の 見つけ役。★施設名と 日付は 飼育個体情報から 取る
    kakeizu = load_kakeizu(P("data", "derived", "kakeizu_individuals.csv"))

    ents = load_json(P("data", "derived", "entities.json"))
    conflicts = ents.get("conflicts", [])

    bundle = {
        "builtAt": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "prefectures": PREFS,
        "beliefs": stories["beliefs"],
        "keywords": keywords,
        "facts": facts["facts"],
        "rejected": facts["rejected"],
        "stories": stories["stories"],
        "prefStories": bridge_to_topic(build_pref_stories(rows, meibutsu, zoos, kakeizu)),
        "today": stamp_today(build_today(rows)),
    }
    all_stories = (bundle["stories"] + bundle["prefStories"]
                   + [x for v in bundle["today"].values() for x in v])
    # 本題に出す「数字の絵図」(値は参照している事実の中のものだけ / validate.py が検査する)
    n_fig = figs.attach(all_stories)
    # 「数字が割れているところ」は画面に一覧で出さず、噺のなかの「噂ですが」の一言として使う
    n_uwasa = report.attach_uwasa(all_stories, conflicts)

    out = P("app", "data", "bundle.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* 自動生成: python tools/build.py  (手で編集しない) */\n")
        f.write("window.HANASHI = ")
        json.dump(bundle, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    n_today = sum(len(v) for v in bundle["today"].values())
    print("built:", out)
    print("  keywords", len(bundle["keywords"]))
    print("  facts", len(bundle["facts"]), "/ stories", len(bundle["stories"]),
          "/ prefStories", len(bundle["prefStories"]), "/ today", n_today, "items on", len(bundle["today"]), "days")
    n_all = len(bundle["stories"]) + len(bundle["prefStories"]) + n_today
    n_serifu = sum(1 for s in all_stories if any(not isinstance(h, str) for h in s.get("hondai", [])))
    print("  絵図つき", n_fig, "/", n_all, "席  噂の一言つき", n_uwasa, "席  台詞入り", n_serifu, "席")
    # ★書き出しは 文字列の本題を 前提に している → 台詞を ならしてから 渡す
    # ★v2: 園ごとの入口 (?kin=<slug>)。家系図から作った園マスタを画面へ渡す
    kin_src = P("data", "derived", "kakeizu_zoos.json")
    kin = load_json(kin_src) if os.path.exists(kin_src) else {"items": []}
    kout = P("app", "data", "kin.js")
    with open(kout, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* 自動生成: python tools/build.py  (手で編集しない) */\n")
        f.write("window.HANASHI_KIN = ")
        json.dump(kin, f, ensure_ascii=False)
        f.write(";\n")
    print("  入口 (園):", len(kin.get("items", [])), "件")

    dst, n = report.write_report(facts, flatten_hondai(all_stories), conflicts, ents.get("entities", []))
