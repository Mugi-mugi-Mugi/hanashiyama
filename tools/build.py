def normalize_scenes(stories):
    """台本の scenes を ★場面の 配列 {head, from, to, img?, label?} に そろえる (2026-11-15)。
    ★生成側の [1枚目, 2枚目] (写真の 指定) は 本題を 半分に 割った 2 場面の 頭に 置く (★今までと 同じ 位置)。
    ★県の噺「〇〇へ 渡った記録」型 (記録に 他園移動園館 が ある 席) は、写真の 説明から ★園名を 外す
      (名札「西山動物園の」が 振りの 問い「どこの園から?」の 答えを 先に 言うため。2026-11-15 ユーザー判断)"""
    n = 0
    for st in stories:
        hon_n = len(st.get("hondai") or [])
        sc = st.get("scenes")
        moved = any("他園移動園館" in (e or {}) for e in (st.get("evidence") or []) if isinstance(e, dict))
        if sc is None and moved:
            sc = ["panda", None]
        if isinstance(sc, list) and (not sc or not isinstance(sc[0], dict)):
            k1, k2 = (list(sc) + [None, None])[:2]
            if hon_n < 2:
                new = [{"head": "", "from": 0, "to": max(0, hon_n - 1)}]
                if k1: new[0]["img"] = k1
            else:
                h = (hon_n + 1) // 2
                new = [{"head": "", "from": 0, "to": h - 1}, {"head": "", "from": h, "to": hon_n - 1}]
                if k1: new[0]["img"] = k1
                if k2: new[1]["img"] = k2
            if moved:
                for x in new:
                    if x.get("img") == "panda":
                        x["label"] = "レッサーパンダ"
            st["scenes"] = new
            n += 1
    return n


