def stamp_today(today):
    """★暦の噺に「自分が 何月何日の 噺か」と「暦の噺である」印を 持たせる。

    ★2026-09-25: 暦の噺を ★その日 以外でも 出せるように した (手前 7 日 / 好きなものから)。
      ★出す側が「今日の噺か どうか」を 見分けられないと、
      ★「今日という日の話を」と 言いながら 今日で ない、が 起きる。
    """
    # ★手がかり (思い込み) が 付いていないと、★好きなものから 引けない。
    #   ★暦の噺は これまで「その日に 開いた人」にしか 届かなかった。
    #   ★2026-09-25: 好きなものから「こういう情報も ございます」として 出せるように する。
    HOOKS = {
        "T-1128": ["b_bakumatsu"],          # 命日 … 歴史・侍・お墓・悪役
        "T-0505": ["b_park_boring"],        # いちばん多かった日 … 混み具合
        "T-0124": ["b_snow_nothing"],       # 0 人の日 … 雪・寒い
        "T-pandaday": ["b_panda_bw"],       # 名前の由来 … パンダ
        "T-1007": ["b_panda_bw"],           # 双子の一般公開 … パンダ
    }
    for md, arr in today.items():
        for s in arr:
            s["md"] = md
            s["isToday"] = True
            h = s.setdefault("hooks", {"prefectures": [], "beliefs": []})
            h.setdefault("prefectures", [])
            if not h.get("beliefs"):
                for key, bl in HOOKS.items():
                    if s["id"].startswith(key):
                        h["beliefs"] = list(bl)
                        break
                else:
                    h["beliefs"] = []
    return today


def bridge_to_topic(stories):
    """★県の噺の 入りに「名物 → お題」の つなぎを 足す (2026-09-24)。

    ★直した理由 (ユーザー指摘)
      県の噺の bridge は「青森県からでございますか。十和田湖の。」という ★相づち だけで、
      すぐ 振り「名所と呼ばれる山、はじめは何だったとお思いで。」に 飛んでいた。
      ★十和田湖 から 名所と呼ばれる山 へ ★つなぎが 無い。
      ★手書きの席は bridge が「では、その花見の場所の話を。」と つないでいる。そこに 揃える。

    ★お題は 3 系統 しか 無いので、振りの 語で 見分けて 言い分ける。
    """
    for s in stories:
        f = s.get("furi", "")
        jimoto = "お膝元" in s.get("bridge", "")
        # ★見分ける 順番が 大事。「福井から東京都へ渡ったレッサーパンダ」にも
        #   ★「パンダ」が 入るので、★渡り を 先に 判定する。
        if any(k in f for k in ("渡った", "渡って", "送った", "送り出した", "行き来",
                                "出どころ", "帳面", "道すじ", "つながって")):
            tsunagi = ("この町から 出ていった 子らの話で ひとつ。" if jimoto
                       else "そのお国と この町の、行き来の話で ひとつ。")
        elif any(k in f for k in ("つつじ", "赤くなる", "名所", "山ひとつ")):
            tsunagi = ("足元の 山の話で ひとつ。" if jimoto
                       else "そちらの名所に くらべますと 気が引けますが、うちの山の話で ひとつ。")
        else:
            tsunagi = ("お膝元のお客さんに 今さらでございますが、名前の話で ひとつ。" if jimoto
                       else "名の通ったところからの お客さんに、名前の話で ひとつ。")
        s["bridge"] = s["bridge"].rstrip() + " " + tsunagi
    return stories


